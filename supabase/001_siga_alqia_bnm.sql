create policy "evid_storage_read_owner_or_leader" on storage.objects for select to authenticated
  using (bucket_id='evidencias'
    and (owner_id=(select auth.uid())::text or (select private.is_coordinator())));
create policy "evid_storage_upload_owner" on storage.objects for insert to authenticated
  with check (bucket_id='evidencias' and owner_id=(select auth.uid())::text);
create policy "evid_storage_delete_leader" on storage.objects for delete to authenticated
  using (bucket_id='evidencias' and (select private.is_coordinator()));

create policy "avatar_storage_read_owner_or_leader" on storage.objects for select to authenticated
  using (bucket_id='avatars' and
    (owner_id=(select auth.uid())::text or (select private.is_coordinator())));

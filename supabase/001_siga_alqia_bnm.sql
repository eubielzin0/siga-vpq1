    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='coletas'
  ) then alter publication supabase_realtime add table public.coletas; end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='turnos'
  ) then alter publication supabase_realtime add table public.turnos; end if;
end $$;


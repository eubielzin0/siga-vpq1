begin;

create schema if not exists private;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null default '',
  funcao text not null default 'Auditor(a)',
  papel text not null default 'auditor' check (papel in ('auditor','coordenador')),
  telefone text,
  nascimento date,
  admissao date,
  avatar_path text,
  criado_em timestamptz not null default now()
);

create table if not exists public.lojas (
  luc text primary key,
  nome text not null,
  pavimento text not null,
  bloco text,
  ordem_rota integer not null default 0,
  segmento text,
  ativa boolean not null default true,
  criado_em timestamptz not null default now()
);
create index if not exists lojas_rota_idx on public.lojas(pavimento, bloco, ordem_rota) where ativa;

create table if not exists public.coletas (
  id bigint generated by default as identity primary key,
  auditor_id uuid not null references public.profiles(id),
  auditor_nome text not null,
  rota text not null,
  data date not null,
  loja text not null,
  luc text references public.lojas(luc),
  status text not null check (status in ('coletado','impedimento')),
  motivo text,
  marcado_em timestamptz not null default now(),
  unique (auditor_id,rota,data,loja)
);
create index if not exists coletas_dia_idx on public.coletas(data,rota);

create table if not exists public.turnos (
  id bigint generated by default as identity primary key,
  auditor_id uuid not null references public.profiles(id),
  auditor_nome text not null,
  auditor_funcao text,
  rota text not null,
  data date not null,
  total integer not null default 0,
  coletadas integer not null default 0,
  impedimentos integer not null default 0,
  pendentes integer not null default 0,
  checklist_ok integer not null default 0,
  checklist_total integer not null default 0,
  finalizado_em timestamptz,
  unique (auditor_id,rota,data)
);
create index if not exists turnos_dia_idx on public.turnos(data,rota);

create table if not exists public.evidencias (
  id bigint generated by default as identity primary key,
  auditor_id uuid not null references public.profiles(id),
  auditor_nome text not null,
  rota text not null,
  data date not null,
  loja text not null,
  luc text references public.lojas(luc),
  tipo text not null check (tipo in ('POS','Sistema')),
  path text not null unique,
  tamanho bigint not null default 0,
  criado_em timestamptz not null default now()
);
create index if not exists evidencias_dia_idx on public.evidencias(data,loja);

-- O helper de autorização está fora de public e consulta APENAS o papel do próprio usuário.
-- SECURITY DEFINER é necessário aqui para não causar recursão nas políticas de profiles.
create or replace function private.is_coordinator()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and papel = 'coordenador'
  );
$$;

create or replace function private.create_profile_on_signup()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, nome, funcao, papel)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'nome',''),split_part(new.email,'@',1)),
    'Auditor(a)',
    'auditor'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists siga_profile_on_auth_user on auth.users;
create trigger siga_profile_on_auth_user
after insert on auth.users
for each row execute function private.create_profile_on_signup();

revoke all on schema private from public, anon;
grant usage on schema private to authenticated;
revoke all on function private.is_coordinator() from public, anon;
grant execute on function private.is_coordinator() to authenticated;
revoke all on function private.create_profile_on_signup() from public, anon, authenticated;

-- Nenhuma tabela operacional aceita acesso anônimo.
revoke all on public.profiles, public.lojas, public.coletas, public.turnos, public.evidencias
  from public, anon, authenticated;
grant select on public.profiles, public.lojas, public.coletas, public.turnos, public.evidencias to authenticated;
grant update (telefone,nascimento,admissao,avatar_path) on public.profiles to authenticated;
grant insert, update, delete on public.lojas, public.coletas, public.turnos, public.evidencias to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.profiles enable row level security;
alter table public.lojas enable row level security;
alter table public.coletas enable row level security;
alter table public.turnos enable row level security;
alter table public.evidencias enable row level security;

create policy "profiles_read_self_or_leader" on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select private.is_coordinator()));
create policy "profiles_update_self" on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy "lojas_read_logged_in" on public.lojas for select to authenticated using (true);
create policy "lojas_insert_leader" on public.lojas for insert to authenticated
  with check ((select private.is_coordinator()));
create policy "lojas_update_leader" on public.lojas for update to authenticated
  using ((select private.is_coordinator())) with check ((select private.is_coordinator()));
create policy "lojas_delete_leader" on public.lojas for delete to authenticated
  using ((select private.is_coordinator()));

create policy "coletas_read_self_or_leader" on public.coletas for select to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "coletas_insert_self_or_leader" on public.coletas for insert to authenticated
  with check (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "coletas_update_self_or_leader" on public.coletas for update to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()))
  with check (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "coletas_delete_self_or_leader" on public.coletas for delete to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()));

create policy "turnos_read_self_or_leader" on public.turnos for select to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "turnos_insert_self_or_leader" on public.turnos for insert to authenticated
  with check (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "turnos_update_self_or_leader" on public.turnos for update to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()))
  with check (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "turnos_delete_self_or_leader" on public.turnos for delete to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()));

create policy "evidencias_read_self_or_leader" on public.evidencias for select to authenticated
  using (auditor_id = (select auth.uid()) or (select private.is_coordinator()));
create policy "evidencias_insert_self" on public.evidencias for insert to authenticated
  with check (auditor_id = (select auth.uid()));
create policy "evidencias_delete_leader" on public.evidencias for delete to authenticated
  using ((select private.is_coordinator()));

